const {chromium} = await import(process.env.MODEL_SURVEY_PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const root=new URL('../.local/qa/',import.meta.url).pathname;
await fs.mkdir(root,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.MODEL_SURVEY_BROWSER,headless:true,chromiumSandbox:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:62099/?view=1',{waitUntil:'networkidle'});
 page.setDefaultTimeout(10000);
 const click=async name=>page.getByRole('button',{name,exact:true}).click();
 await click('Expand');
 assert.equal(await page.locator('.sv-asset').count(),93);
 assert.equal(await page.locator('.sv-asset>summary .sv-preview-button').count(),92);
 assert.equal(await page.locator('.sv-asset>summary .sv-preview-missing').count(),1);
 await page.locator('.sv-asset>summary img').evaluateAll(async imgs=>{imgs.forEach(im=>im.loading='eager');await Promise.all(imgs.map(im=>im.decode()));});
 assert.equal(await page.locator('.sv-asset>summary img').evaluateAll(imgs=>imgs.filter(x=>!x.complete||x.naturalWidth===0).length),0);
 await click('Collapse');
 const search=page.getByRole('searchbox');await search.fill('trachea');
 await click('Preview Trachea / Y-airway');
 const dialog=page.getByRole('dialog');await dialog.waitFor();
 await dialog.locator('.sv-preview-stage img').evaluate(img=>img.decode());
 assert.match(await dialog.innerText(),/Fresh neutral GLB preview/);
 assert.equal(await page.locator('.sv-asset[open]').count(),0);
 const original=await dialog.locator('.sv-preview-stage img').getAttribute('src');
 await click('Next view');assert.notEqual(await dialog.locator('.sv-preview-stage img').getAttribute('src'),original);
 await page.keyboard.press('ArrowLeft');assert.equal(await dialog.locator('.sv-preview-stage img').getAttribute('src'),original);
 await click('Zoom image');assert.ok(await dialog.locator('.sv-preview-zoom').isVisible());await click('Fit image');
 await page.screenshot({path:root+'preview-dialog-desktop.png',fullPage:false});
 await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0);
 await search.fill('fetus');assert.ok(await page.locator('.sv-preview-missing').isVisible());
 await page.locator('.sv-asset>summary').click();assert.ok(await page.getByText('Recipe only · no retained model or review pixels',{exact:true}).isVisible());
 await search.fill('kidney_left');await click('Preview Left kidney');assert.ok(await page.getByRole('dialog').getByText('Retained review image',{exact:true}).isVisible());
 await click('Close preview');
 await search.fill('');await click('Collapse');await page.locator('.sv-group>summary').filter({hasText:'Oral & dental'}).click();
 await page.waitForTimeout(200);await page.screenshot({path:root+'preview-tree-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);await page.screenshot({path:root+'preview-tree-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));assert.equal(overflow.width,overflow.scroll);
 await click('Preview Adult teeth & gingiva');await page.getByRole('dialog').locator('.sv-preview-stage img').evaluate(img=>img.decode());
 await page.screenshot({path:root+'preview-dialog-mobile.png',fullPage:false});
 const dialogOverflow=await page.getByRole('dialog').evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth}));assert.ok(dialogOverflow.scroll<=dialogOverflow.width+1);
 await page.emulateMedia({colorScheme:'dark'});await page.waitForTimeout(200);await page.screenshot({path:root+'preview-dialog-dark.png',fullPage:false});
 await click('Close preview');await page.emulateMedia({colorScheme:'light'});await page.setViewportSize({width:1440,height:1000});
 await search.fill('');await click('Preview Adult teeth & gingiva');const label=await page.locator('#sv-preview-title').innerText();await click('Next model');assert.notEqual(await page.locator('#sv-preview-title').innerText(),label);await click('Previous model');assert.equal(await page.locator('#sv-preview-title').innerText(),label);await click('Close preview');
 for(const tab of ['Purpose','Review']){await click(tab);await click('Expand');assert.equal(await page.locator('.sv-asset>summary .sv-preview-button').count(),92);}
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({status:'passed',rows:93,previewRows:92,missing:'fetus recipe only',checks:['all thumbnails decode','no row toggle on preview','fresh/retained labels','view and keyboard navigation','zoom/fit','Escape and close','missing preview','model navigation','three tree slices','390px tree/modal reflow','light/dark rendering'],errors,overflow,dialogOverflow}));
}finally{await browser.close();}
